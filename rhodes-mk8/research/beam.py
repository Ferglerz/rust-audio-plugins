"""Generate mass-normalized MK8 harp modes from a tapered steel beam and tuning mass.

The manufacturer sells compatible full-length blanks. Until a current cutting card
is available the scale comes from the documented compatible replacement table in
Stage 73. No Stage 73 voicing, modal envelopes or waveform is used.
Run from the workspace root. Requires Python 3, NumPy and SciPy.
"""
from pathlib import Path
import re
import numpy as np
from scipy.linalg import eigh

root=Path(__file__).resolve().parents[2]
stage=(root/'stage73/src/calibration.rs').read_text()
lengths=[float(x) for x in re.findall(r'^\s+\[([\d.]+),', stage,re.M)[:73]]
assert len(lengths)==73
N=12
E,RHO=2.0e11,7850.


def hermite(u,h):
    return np.array([1-3*u*u+2*u**3, (u-2*u*u+u**3)*h, 3*u*u-2*u**3, (-u*u+u**3)*h])


def shapes(length_mm,n):
    reg=(n-28)/72
    L=length_mm*.001
    h=L/N
    ncoord=2*(N+1)
    K,M=np.zeros((ncoord,ncoord)),np.zeros((ncoord,ncoord))
    # A swaged replacement is thicker near the head than near the free end.
    # No MK8 taper drawing has been published. Diameters below are priors.
    dia=.00148
    for i in range(N):
        xi=(i+.5)/N
        d=dia*(1+.85*max(0,1-xi*L/.014))
        A=np.pi*d*d/4
        inertia=np.pi*d**4/64
        ids=np.arange(2*i,2*i+4)
        K[np.ix_(ids,ids)]+=E*inertia/h**3*np.array([
            [12,6*h,-12,6*h],[6*h,4*h*h,-6*h,2*h*h],[-12,-6*h,12,-6*h],[6*h,2*h*h,-6*h,4*h*h]])
        M[np.ix_(ids,ids)]+=RHO*A*h/420*np.array([
            [156,22*h,54,-13*h],[22*h,4*h*h,13*h,-3*h*h],[54,13*h,156,-22*h],[-13*h,-3*h*h,-22*h,4*h*h]])
    def observe(frac):
        s=min(frac*N,N-1e-12);i=int(s)
        v=np.zeros(ncoord);v[2*i:2*i+4]=hermite(s-i,h)
        return v[2:]
    # A tuning spring acts at a point on the shaft and couples all bending
    # modes through its mass. Clamp displacement and rotation at the tone block.
    K=K[2:,2:];M=M[2:,2:]
    point=observe(.93)
    M+=.00036*(.35**reg)*np.outer(point,point)
    w2,modes=eigh(K,M,subset_by_index=[0,3])
    # Manufacturing and sliding the spring tunes the lowest mode. Retain the
    # predicted frequency ratios, absolute point mobilities and their signs.
    w=np.sqrt(w2)
    hit=observe(.27+.23*reg)@modes
    tip=observe(1.)@modes
    return list(zip(w/w[0],hit,tip))

if __name__=='__main__':
    rows=['//! Generated by research/beam.py. [frequency ratio, hammer, tip] for four modes.',
          '#[rustfmt::skip]', 'pub(super) const MODES: [[[f64;3];4];73] = [']
    for n,L in enumerate(lengths,28):
        entries=', '.join(f'[{f:.8f}, {hammer:.8f}, {tip:.8f}]' for f,hammer,tip in shapes(L,n))
        rows.append(f'    [{entries}],')
    rows.append('];')
    (root/'rhodes-mk8/src/modes.rs').write_text('\n'.join(rows)+'\n')
