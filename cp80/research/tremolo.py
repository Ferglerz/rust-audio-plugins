"""Check oscillator frequency, alternating LED drive and estimated light-cell modulation."""

import subprocess
import tempfile
from pathlib import Path

import numpy as np
from scipy.signal import find_peaks

TEMPLATE = Path(__file__).with_name("tremolo.cir").read_text()


def simulate(speed, trim=17800):
    deck = TEMPLATE.replace("speed=1 vr7=17.8k", f"speed={speed} vr7={trim}")
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory, "osc.cir")
        path.write_text(deck)
        subprocess.run(
            ["ngspice", "-b", path],
            cwd=directory,
            check=True,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        data = np.loadtxt(Path(directory, "oscillator.txt"))
    t = np.arange(12, 20, 0.001)
    osc, led1, led2 = [np.interp(t, data[:, 0], s) for s in data[:, 1:].T]
    peaks, _ = find_peaks(osc, prominence=0.2)
    if len(peaks) < 3:
        raise ValueError("oscillator did not start")
    hz = (len(peaks) - 1) / (t[peaks[-1]] - t[peaks[0]])
    return hz, osc, np.c_[led1, led2]


def generate():
    cycles = []
    for speed in (0, 0.5, 1):
        hz, osc, currents = simulate(speed)
        peaks, _ = find_peaks(osc, prominence=0.2, plateau_size=True)
        lo, hi = peaks[-2:]
        phases = np.linspace(lo, hi, 64, endpoint=False)
        # Both drivers share the same oscillator trigger. The second op-amp
        # inverts the waveform, which need not have half-wave symmetry.
        current = np.array([
            np.interp(phases, np.arange(len(currents)), channel) for channel in currents.T
        ])
        current /= current.mean()
        rms_dbm = 10 * np.log10(np.var(osc) / 0.6)
        print(
            f"speed {speed}  {hz:.3f} Hz  TP {rms_dbm:.2f} dBm  LED correlation {np.corrcoef(currents.T)[0, 1]:.6f}"
        )
        cycles.append((hz, current))
    rows = []
    for hz, channels in cycles:
        traces = ["[" + ", ".join(f"{x:.8f}" for x in trace) + "]" for trace in channels]
        rows.append(f"({hz:.8f}, [\n    " + ",\n    ".join(traces) + "\n])")
    path = Path(__file__).resolve().parents[1] / "src" / "lfo_table.rs"
    path.write_text(
        "// Generated by research/tremolo.py from Yamaha's RC4558 oscillator and LED drivers.\n#[rustfmt::skip]\npub const CYCLES: [(f64, [[f64; 64]; 2]); 3] = [\n"
        + ",\n".join(rows)
        + "\n];\n"
    )
    if not (
        0.6 <= cycles[0][0] <= 1.3
        and 9 <= cycles[2][0] <= 11
        and abs(rms_dbm - 16) <= 0.5
    ):
        raise SystemExit("factory oscillator range or TP trim missed")


if __name__ == "__main__":
    generate()
