"""Regenerate the three normalized Jordan oscillator cycles from its SPICE deck."""

import subprocess
import tempfile
from pathlib import Path

import numpy as np
from scipy.signal import find_peaks

HERE = Path(__file__).resolve().parent


def oscillator(ohms, wd):
    src = (HERE / "jordan_lfo.cir").read_text().replace("@RATE@", str(ohms))
    (wd / "osc.cir").write_text(src)
    subprocess.run(
        ["ngspice", "-b", "osc.cir"], cwd=wd, stdout=subprocess.DEVNULL, check=True
    )
    t, y = np.loadtxt(wd / "oscillator.txt").T
    t, y = t[t > 3], y[t > 3]
    # Align at minimum collector voltage so phase stays coherent across speeds.
    minima = find_peaks(-y, prominence=1)[0]
    periods = np.diff(t[minima])
    begin, end = t[minima[-2:]]
    wave = np.interp(np.linspace(begin, end, 64, endpoint=False), t, y)
    return 1 / np.mean(periods), (wave - min(wave)) / np.ptp(wave)


if __name__ == "__main__":
    lines = [
        "// Generated by research/jordan_lfo.py from factory figure 11-17.",
        "#[rustfmt::skip]",
        "pub(super) const CYCLES: [(f64, [f64; 64]); 3] = [",
    ]
    with tempfile.TemporaryDirectory() as tmp:
        for r in (102200, 12200, 2200):
            hz, cycle = oscillator(r, Path(tmp))
            lines.append(f"    ({hz:.7f}, [")
            for i in range(0, 64, 8):
                lines.append(
                    "        " + ", ".join(f"{v:.7f}" for v in cycle[i : i + 8]) + ","
                )
            lines.append("    ]),")
    lines.append("];")
    (HERE.parent / "src/jordan_lfo.rs").write_text("\n".join(lines) + "\n")
