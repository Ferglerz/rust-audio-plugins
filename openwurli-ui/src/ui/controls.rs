use Knob::*;

pub(super) fn visible(model: PianoType, era: Era, peterson: bool) -> &'static [Knob] {
    match model {
        PianoType::Wurli => &[
            HammerHardness,
            ReedDecay,
            PickupHeight,
            PickupDrive,
            Tremolo,
            TremoloResponse,
            Speaker,
        ],
        PianoType::Stage if era == Era::Sparkletop => &[
            TineHeight,
            PickupGap,
            Preamp,
            JordanBass,
            JordanTreble,
            Rate,
            Depth,
        ],
        PianoType::Stage if peterson => &[TineHeight, PickupGap, VibratoSpeed, Intensity],
        PianoType::Stage => &[TineHeight, PickupGap, StageVolume, StageTone, Cable],
        PianoType::Grand => &[JackVolume, Bass, Middle, Treble, Speed, GrandDepth],
    }
}

