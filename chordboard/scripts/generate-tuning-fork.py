#!/usr/bin/env python3
"""Convert the sourced tuning-fork SVG path to femtovg; builds need no Python."""
import re
import xml.etree.ElementTree as ET
from pathlib import Path

root = Path(__file__).resolve().parents[1]
svg = ET.parse(root / 'assets/icons/tuning-fork.svg').getroot()
data = svg.find('{http://www.w3.org/2000/svg}path').attrib['d']
tokens = re.findall(r'[A-Za-z]|[-+]?(?:\d*\.\d+|\d+)', data)
i, x, y, start, control, previous, subpath = 0, 0., 0., (0., 0.), None, None, -1
lines = ['// Generated by scripts/generate-tuning-fork.py; SVG Repo, CC0.',
         'use nih_plug_vizia::vizia::vg::{Path, Solidity};',
         'pub(super) fn path() -> Path {', '    let mut p = Path::new();']


def emit(method, *values):
    # Normalize SVG viewBox to the same 24px coordinate system as Tabler.
    numbers = [str(round(v * 24 / 512, 5)) for v in values]
    lines.append(f'    p.{method}(' + ', '.join(numbers) + ');')


while i < len(tokens):
    if tokens[i].isalpha():
        command = tokens[i]
        i += 1
    upper = command.upper()
    if upper == 'Z':
        lines.append('    p.close();')
        if subpath > 0:
            lines.append('    p.solidity(Solidity::Hole);')
        x, y = start
        control = None
        previous = upper
        continue
    count = {'M': 2, 'L': 2, 'H': 1, 'V': 1, 'C': 6, 'S': 4}[upper]
    args = list(map(float, tokens[i:i+count]))
    i += count
    if command.islower():
        args = [v + (x if k % 2 == 0 else y) for k, v in enumerate(args)] if upper not in ('H', 'V') else [args[0] + (x if upper == 'H' else y)]
    if upper in ('M', 'L'):
        x, y = args
        emit('move_to' if upper == 'M' else 'line_to', x, y)
        if upper == 'M':
            start = x, y
            subpath += 1
            command = 'l' if command.islower() else 'L'
    elif upper in ('H', 'V'):
        x, y = (args[0], y) if upper == 'H' else (x, args[0])
        emit('line_to', x, y)
    else:
        if upper == 'S':
            first = (2*x-control[0], 2*y-control[1]) if previous in ('C', 'S') else (x, y)
            args = [*first, *args]
        emit('bezier_to', *args)
        control = args[2], args[3]
        x, y = args[4:]
    previous = upper
lines += ['    p', '}', '']
(root / 'src/ui/tuning_fork.rs').write_text('\n'.join(lines))
